-- ============================================================
-- GYMTRACK · Esquema para Supabase (PostgreSQL)
-- Pégalo completo en Supabase → SQL Editor → Run. Es seguro volver a ejecutarlo.
-- ============================================================

create or replace function gt_now() returns text
language sql stable as $$ select to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

create table if not exists users (
  id integer generated by default as identity primary key,
  email text not null,
  pass_hash text not null,
  role text not null default 'client' check (role in ('client','trainer')),
  first_name text not null,
  last_name text not null default '',
  birth_date text,
  phone text,
  photo text,
  avatar text,
  plan text not null default 'free' check (plan in ('free','premium')),
  plan_until text,
  coach_notes text not null default '',
  active integer not null default 1,
  created_at text not null default gt_now()
);
create unique index if not exists users_email_key on users (lower(email));

create table if not exists profiles (
  user_id integer primary key references users(id) on delete cascade,
  gender text, height_cm double precision, weight_kg double precision, body_fat double precision, muscle_mass double precision,
  waist double precision, hip double precision,
  level text, freq integer, days text not null default '[]', duration integer,
  place text, training_type text, injuries text
);

create table if not exists goals (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  kind text not null,
  title text not null,
  metric text,
  start_value double precision,
  target_value double precision,
  progress integer not null default 0,
  done integer not null default 0,
  created_at text not null default gt_now()
);
create index if not exists idx_goals_user on goals(user_id);

create table if not exists measurements (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  date text not null,
  weight double precision, body_fat double precision, muscle_mass double precision, waist double precision, hip double precision,
  notes text
);
create index if not exists idx_meas_user on measurements(user_id, date);

create table if not exists progress_photos (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  file text not null,
  date text not null,
  note text
);
create index if not exists idx_photos_user on progress_photos(user_id);

create table if not exists exercises (
  id integer generated by default as identity primary key,
  name text not null,
  muscle text not null,
  equipment text,
  description text,
  video_url text,
  created_at text not null default gt_now()
);
create index if not exists idx_exercises_name on exercises(lower(name));

create table if not exists routines (
  id integer generated by default as identity primary key,
  name text not null,
  description text,
  level text,
  goal text,
  tier text not null default 'premium' check (tier in ('free','premium')),
  days text not null default '[]',
  created_at text not null default gt_now(),
  updated_at text not null default gt_now()
);

create table if not exists client_routines (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  routine_id integer not null references routines(id) on delete cascade,
  assigned_at text not null default gt_now(),
  unique (user_id, routine_id)
);
create index if not exists idx_cr_routine on client_routines(routine_id);

create table if not exists diets (
  id integer generated by default as identity primary key,
  name text not null,
  description text,
  calories integer, protein integer, carbs integer, fat integer,
  meals text not null default '[]',
  created_at text not null default gt_now(),
  updated_at text not null default gt_now()
);

create table if not exists client_diets (
  user_id integer primary key references users(id) on delete cascade,
  diet_id integer not null references diets(id) on delete cascade,
  notes text,
  assigned_at text not null default gt_now()
);
create index if not exists idx_cd_diet on client_diets(diet_id);

create table if not exists workout_logs (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  routine_id integer,
  routine_name text,
  day_index integer,
  day_name text,
  date text not null,
  duration_min integer not null default 0,
  created_at text not null default gt_now()
);
create index if not exists idx_logs_user on workout_logs(user_id, date);

create table if not exists payments (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  amount double precision not null,
  method text not null,
  months integer not null default 1,
  note text,
  date text not null,
  created_at text not null default gt_now()
);
create index if not exists idx_payments_user on payments(user_id);

create table if not exists notifications (
  id integer generated by default as identity primary key,
  user_id integer not null references users(id) on delete cascade,
  text text not null,
  read integer not null default 0,
  created_at text not null default gt_now()
);
create index if not exists idx_notif_user on notifications(user_id);

create table if not exists sessions (
  token_hash text primary key,
  user_id integer not null references users(id) on delete cascade,
  expires_at double precision not null
);
create index if not exists idx_sessions_user on sessions(user_id);

create table if not exists reset_tokens (
  token_hash text primary key,
  user_id integer not null references users(id) on delete cascade,
  expires_at double precision not null
);
create index if not exists idx_reset_user on reset_tokens(user_id);

create table if not exists settings (
  key text primary key,
  value text not null default ''
);

-- Límite de intentos (login, registro…) compartido entre todas las instancias del servidor
create table if not exists rate_limits (
  key text primary key,
  n integer not null,
  reset_at double precision not null
);

-- ------------------------------------------------------------
-- Seguridad: la app accede SOLO desde el servidor (función de Netlify).
-- Activamos RLS sin políticas y quitamos permisos a los roles públicos de Supabase,
-- así nadie puede leer ni escribir estas tablas con la clave "anon" desde el navegador.
-- ------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['users','profiles','goals','measurements','progress_photos','exercises','routines',
    'client_routines','diets','client_diets','workout_logs','payments','notifications','sessions','reset_tokens','settings','rate_limits']
  loop
    execute format('alter table public.%I enable row level security', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on public.%I from anon', t);
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
      execute format('revoke all on public.%I from authenticated', t);
    end if;
  end loop;
end $$;

-- Bucket privado para las fotos (perfil y progreso). Solo se ejecuta en Supabase.
do $$
begin
  if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
    insert into storage.buckets (id, name, public) values ('photos', 'photos', false) on conflict (id) do nothing;
  end if;
end $$;
